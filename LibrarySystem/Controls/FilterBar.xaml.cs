using System.ComponentModel;
using System.Data;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Input;
using System.Windows.Threading;
using LibrarySystem.Services;

namespace LibrarySystem.Controls;

/// <summary>Выпадающий фильтр по значению столбца (в данных — «Все» и перечисленные значения). Values = null — список значений берётся из самих данных.</summary>
public sealed record DropFilter(string Column, string[]? Values = null);

/// <summary>
/// Панель фильтров, общая для всех таблиц: поиск по всем столбцам (с «✕» и задержкой ввода, чтобы не лагало),
/// выпадающие фильтры по столбцам, сортировка (список + направление + клик по заголовку) и счётчик записей.
/// Страница вызывает Configure один раз и Bind после каждой загрузки данных — фильтры при этом сохраняются.
/// </summary>
public partial class FilterBar : UserControl
{
    private sealed class DropState
    {
        public DropState(DropFilter spec, ComboBox box) { Spec = spec; Box = box; }
        public DropFilter Spec { get; }
        public ComboBox Box { get; }
        public string Selected { get; set; } = "";
    }

    private static readonly string[] DateWords = { "Дат", "Время", "Выдана", "Срок", "Создан", "Регистрац", "Возвращена" };

    private readonly DispatcherTimer _debounce = new() { Interval = TimeSpan.FromMilliseconds(180) };
    private readonly List<DropState> _drops = new();
    private DataTable? _table;
    private DataGrid? _grid;
    private string? _defaultSort;
    private bool _defaultDesc;
    private string? _sortColumn;
    private bool _desc;
    private bool _updating;

    public FilterBar()
    {
        InitializeComponent();
        _debounce.Tick += (_, _) => Apply();
        UpdateDirectionButton();
    }

    /// <summary>Подключает панель к таблице. defaultSort — столбец сортировки по умолчанию.</summary>
    public void Configure(DataGrid grid, string? defaultSort = null, bool descending = false, params DropFilter[] drops)
    {
        _grid = grid;
        _defaultSort = defaultSort;
        _defaultDesc = descending;
        _sortColumn = defaultSort;
        _desc = descending;

        // клик по заголовку столбца сортирует через эту же панель, чтобы список и стрелка не расходились
        grid.Sorting += OnGridSorting;
        grid.AutoGeneratedColumns += (_, _) => UpdateHeaderArrows();

        DropPanel.Children.Clear();
        _drops.Clear();
        foreach (DropFilter spec in drops)
        {
            var box = new ComboBox { Style = (Style)FindResource("InputCombo"), Width = 150 };
            var state = new DropState(spec, box);
            box.SelectionChanged += (_, _) =>
            {
                if (_updating || box.SelectedItem is not string value) return;
                state.Selected = box.SelectedIndex <= 0 ? "" : value;
                Apply();
            };
            var panel = new StackPanel { Orientation = Orientation.Horizontal, Margin = new Thickness(0, 0, 14, 4) };
            panel.Children.Add(new TextBlock
            {
                Text = spec.Column + ":", Style = (Style)FindResource("Label"), Margin = new Thickness(0, 0, 8, 0),
            });
            panel.Children.Add(box);
            DropPanel.Children.Add(panel);
            _drops.Add(state);
        }
    }

    /// <summary>Передаёт панели свежие данные (после загрузки или обновления). Поиск, фильтры и сортировка сохраняются.</summary>
    public void Bind(DataTable table)
    {
        _table = table;
        _updating = true;
        try
        {
            var columns = table.Columns.Cast<DataColumn>().Select(c => c.ColumnName).ToList();
            SortBox.ItemsSource = columns;
            if (_sortColumn is null || !columns.Contains(_sortColumn)) ResetSortToDefault();
            SortBox.SelectedItem = _sortColumn;
            foreach (DropState d in _drops) FillDrop(d, table);
        }
        finally { _updating = false; }
        Apply();
    }

    /// <summary>Текст в строке поиска (например, запись, найденная через общий поиск).</summary>
    /// <summary>Заранее выбирает значение выпадающего фильтра (например, статус «Просрочена»); вызывается до Bind.</summary>
    public void SelectDrop(string column, string value)
    {
        foreach (DropState d in _drops)
            if (d.Spec.Column == column)
                d.Selected = value;
    }

    public void SetSearch(string text)
    {
        _updating = true;
        SearchBox.Text = text;
        SearchBox.CaretIndex = text.Length;
        _updating = false;
        UpdateChrome();
        Apply();
    }

    /// <summary>Сбросить поиск, фильтры и сортировку на значения по умолчанию.</summary>
    public void Reset()
    {
        _updating = true;
        SearchBox.Text = "";
        foreach (DropState d in _drops)
        {
            d.Selected = "";
            if (d.Box.Items.Count > 0) d.Box.SelectedIndex = 0;
        }
        ResetSortToDefault();
        SortBox.SelectedItem = _sortColumn;
        _updating = false;
        UpdateChrome();
        Apply();
    }

    // ------------------------------------------------------------------ применение

    private void ResetSortToDefault()
    {
        bool valid = _defaultSort is not null && (_table is null || _table.Columns.Contains(_defaultSort));
        _sortColumn = valid ? _defaultSort : null;
        _desc = valid && _defaultDesc;
    }

    private static void FillDrop(DropState d, DataTable table)
    {
        IEnumerable<string> values = d.Spec.Values
            ?? (table.Columns.Contains(d.Spec.Column)
                ? table.Rows.Cast<DataRow>()
                    .Select(r => Convert.ToString(r[d.Spec.Column]) ?? "")
                    .Where(s => s.Length > 0)
                    .Distinct()
                    .OrderBy(s => s, StringComparer.CurrentCultureIgnoreCase)
                : Enumerable.Empty<string>());

        var items = new List<string> { "Все" };
        items.AddRange(values);
        d.Box.ItemsSource = items;

        int index = d.Selected.Length > 0 ? items.IndexOf(d.Selected) : 0;
        if (index < 0) { index = 0; d.Selected = ""; }
        d.Box.SelectedIndex = index;
    }

    private void Apply()
    {
        _debounce.Stop();
        if (_table is null) return;

        var parts = new List<string>();
        foreach (DropState d in _drops)
            if (d.Selected.Length > 0 && _table.Columns.Contains(d.Spec.Column))
                parts.Add($"[{d.Spec.Column}] = '{d.Selected.Replace("'", "''")}'");
        string like = TableFilter.Like(_table, SearchBox.Text);
        if (like.Length > 0) parts.Add($"({like})");

        string filter = string.Join(" AND ", parts);
        string sort = _sortColumn is not null && _table.Columns.Contains(_sortColumn)
            ? $"[{_sortColumn}] {(_desc ? "DESC" : "ASC")}"
            : "";

        DataView view = _table.DefaultView;
        if (view.RowFilter != filter || view.Sort != sort)
        {
            view.RowFilter = filter;
            view.Sort = sort;
        }

        int total = _table.Rows.Count;
        CountText.Text = view.Count == total ? $"Записей: {total}" : $"Найдено: {view.Count} из {total}";
        UpdateDirectionButton();
        UpdateHeaderArrows();
    }

    private (string Asc, string Desc) DirectionLabels()
    {
        if (_table is not null && _sortColumn is not null && _table.Columns.Contains(_sortColumn))
        {
            DataColumn column = _table.Columns[_sortColumn]!;
            if (column.DataType == typeof(long) || column.DataType == typeof(double)) return ("1 → 9", "9 → 1");
            if (DateWords.Any(w => column.ColumnName.Contains(w, StringComparison.OrdinalIgnoreCase)))
                return ("старые → новые", "новые → старые");
        }
        return ("А → Я", "Я → А");
    }

    private void UpdateDirectionButton()
    {
        var (asc, desc) = DirectionLabels();
        DirButton.Content = _desc ? "▼ " + desc : "▲ " + asc;
        DirButton.IsEnabled = _sortColumn is not null;
        DirButton.ToolTip = "Направление сортировки (нажмите, чтобы изменить)";
    }

    private void UpdateHeaderArrows()
    {
        if (_grid is null) return;
        foreach (DataGridColumn column in _grid.Columns)
        {
            bool current = _sortColumn is not null && (column.Header as string) == _sortColumn;
            column.SortDirection = current ? (_desc ? ListSortDirection.Descending : ListSortDirection.Ascending) : null;
        }
    }

    private void UpdateChrome()
    {
        bool has = SearchBox.Text.Length > 0;
        ClearButton.Visibility = has ? Visibility.Visible : Visibility.Collapsed;
        Hint.Visibility = has ? Visibility.Collapsed : Visibility.Visible;
    }

    // ------------------------------------------------------------------ обработчики

    private void OnTextChanged(object sender, TextChangedEventArgs e)
    {
        UpdateChrome();
        if (_updating) return;
        _debounce.Stop();      // пересчёт — когда пользователь на мгновение остановился, а не на каждую букву
        _debounce.Start();
    }

    private void OnSearchKeyDown(object sender, KeyEventArgs e)
    {
        if (e.Key == Key.Enter) { Apply(); e.Handled = true; }
        else if (e.Key == Key.Escape && SearchBox.Text.Length > 0) { OnClear(sender, e); e.Handled = true; }
    }

    private void OnClear(object sender, RoutedEventArgs e)
    {
        _updating = true;
        SearchBox.Text = "";
        _updating = false;
        UpdateChrome();
        Apply();
        SearchBox.Focus();
    }

    private void OnSortChanged(object sender, SelectionChangedEventArgs e)
    {
        if (_updating || SortBox.SelectedItem is not string column) return;
        _sortColumn = column;
        Apply();
    }

    private void OnToggleDirection(object sender, RoutedEventArgs e)
    {
        if (_sortColumn is null) return;
        _desc = !_desc;
        Apply();
    }

    private void OnReset(object sender, RoutedEventArgs e) => Reset();

    private void OnGridSorting(object? sender, DataGridSortingEventArgs e)
    {
        e.Handled = true;
        if (_table is null || e.Column.Header is not string name || !_table.Columns.Contains(name)) return;

        if (name == _sortColumn) _desc = !_desc;
        else { _sortColumn = name; _desc = false; }

        _updating = true;
        SortBox.SelectedItem = _sortColumn;
        _updating = false;
        Apply();
    }
}
