namespace LibrarySystem.Services;

/// <summary>Вид всплывающего уведомления.</summary>
public enum ToastKind
{
    Success,    // операция выполнена (зелёная полоса)
    Info,       // сведения (латунная полоса)
    Warning,    // подсказка пользователю: что-то нужно выбрать или заполнить
    Error,      // операция невозможна по правилам библиотеки (бордовая полоса, висит дольше)
}
